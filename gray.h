/**
 * @file    gray.h
 * @brief   8路灰度传感器驱动头文件 (串行接口)
 * @note    用于白底红线循迹
 *
 *  传感器原理:
 *    - 8 个对管一字排列, 通过阈值电位器区分红色和白色
 *    - 传感器内部将 8 路并行数据转为串行输出
 *
 *  串行协议 (类 74HC165 移位寄存器, 2 线制):
 *    - CLK (MCU→传感器): 高电平更新数据, 低电平 MCU 读取
 *    - DAT (传感器→MCU): 串行数据输出
 *    - 每帧 8 位: 第1个时钟=通道0(bit0), ... 第8个时钟=通道7(bit7)
 *    - 帧间隔 >1ms: 传感器自动归零, 下一帧从通道0重新开始
 *    - CLK 高电平 ≥5μs (给传感器移位寄存器留运算时间)
 *
 *  逻辑反转:
 *    如果实际传感器输出相反 (0=红线, 1=白底),
 *    编译时定义 GRAY_INVERT_LOGIC 即可:
 *      #define GRAY_INVERT_LOGIC
 *
 *  位置计算 (最长连续段 + 中心优先):
 *    - 最长连续段加权平均, 等长时优先选靠近阵列中心的段
 *    - 映射到 0~160 范围, 80=中心 (兼容 Motor_LineFollow)
 *
 *  红线循迹注意事项:
 *    红线与白底的对比度低于黑线与白底, 需仔细调节每个通道的
 *    电位器阈值. 建议在赛道上实际测试每个传感器通道的响应,
 *    确保所有通道对红线都能可靠触发.
 *
 *  接线 (2 线制, 见 hw_config.h):
 *    GRAY_CLK (PA11) → 传感器 CLK
 *    GRAY_DAT (PA10) → 传感器 DAT (开漏, 需插 PULL 跳线帽)
 *    GND             → 传感器 GND
 */

#ifndef GRAY_H
#define GRAY_H

#include <stdint.h>
#include <stdbool.h>
#include "Board/car_config.h"

/* ===================================================================== *
 *  常量定义                                                                *
 * ===================================================================== */

/** 灰度传感器通道数 (由 Board/car_config.h 定义) */

/** 位置输出范围: 兼容 OpenMV QQVGA 的 x 坐标 (0~160, 中心=80) */
#define GRAY_POS_MIN          0
#define GRAY_POS_MAX          160
#define GRAY_POS_CENTER       80

/* ===================================================================== *
 *  API 函数                                                               *
 * ===================================================================== */

/**
 * @brief 初始化 8 路灰度传感器 GPIO
 * @note  配置所有 8 个通道引脚为上拉输入模式
 *        传感器输出高=检测到红线, 需在 SysConfig 中或手动配置
 */
void Gray_Init(void);

/**
 * @brief 读取 8 通道原始值
 * @param raw 输出数组 [8], 每个元素 0(白/背景) 或 1(红线/深色)
 */
void Gray_ReadRaw(uint8_t raw[GRAY_CHANNEL_COUNT]);

/**
 * @brief 计算红线中心位置 (加权平均)
 * @return 线位置 0~160:
 *         - 0   = 线在最左侧 (通道0)
 *         - 80  = 线在正中心 (通道3~4之间)
 *         - 160 = 线在最右侧 (通道7)
 *         - 无线时返回上次有效位置 (初始=80)
 */
int16_t Gray_GetPosition(void);

/**
 * @brief 获取当前检测到红线的通道数
 * @return 检测到红线的通道数量 (0~8)
 */
uint8_t Gray_GetLineCount(void);

/**
 * @brief 获取最近一次读取的原始传感器值 (调试用)
 * @return 8 位值, bit0=通道0, bit7=通道7, 1=检测到红线
 */
uint8_t Gray_GetRawByte(void);

#endif /* GRAY_H */
